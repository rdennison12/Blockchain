from typing import Any, Dict, List, Optional


class TransactionPool:
    def __init__(self) -> None:
        self.transaction_map: Dict[str, Any] = {}

    def set_transaction(self, transaction: Any) -> None:
        """
        Set or update a transaction in the transaction pool.

        :param transaction: The transaction instance to store.
        """
        self.transaction_map[transaction.id] = transaction

    def existing_transaction(self, address: str) -> Optional[Any]:
        """
        Find a transaction generated by the specified address in the pool.

        :param address: The sender address to match against transaction inputs.
        :return: The matching transaction instance if found, otherwise None.
        """
        for transaction in self.transaction_map.values():
            if transaction.input.get('address') == address:
                return transaction
        return None

    def transaction_data(self) -> List[Dict[str, Any]]:
        """
        Return the serialized data of all transactions currently in the pool.

        :return: A list of dictionaries representing the transaction data.
        """
        return [
            transaction.to_json()
            for transaction in self.transaction_map.values()
        ]

    def clear_blockchain_transactions(self, blockchain: Any) -> None:
        """
        Remove transactions that have already been recorded in the blockchain.

        :param blockchain: The blockchain containing committed blocks.
        """
        for block in blockchain.chain:
            for transaction in block.data:
                self.transaction_map.pop(transaction.get('id'), None)
